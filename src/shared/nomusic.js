// Музыка убрана из продукта (решение владельца 25 сентября: лицензионную музыку в соцсети без
// риска блокировки не вставить, сгенерированная звучит дёшево; звук добавляют при публикации).
//
// Выбора трека нет нигде, но у старых лотов и обзоров трек остался сохранённым — у двух обзоров
// Audi A6 это «балканский трэп» на 5%. Поэтому трек снимается на входе в ролик: в рендере
// (server/app.mjs) и в превью (app/Preview.tsx, ReviewTool). Сам механизм музыки
// (src/shared/music.tsx) не тронут и проверяется рендер-тестами с явно заданным треком —
// при появлении лицензии вернуть музыку значит убрать вызовы withoutMusic.

/** Явное «без музыки»: пустой трек перекрывает и сохранённый, и трек рынка */
export const NO_MUSIC = {track: null};

/** Лот или обзор без музыки — что бы в нём ни было сохранено */
export const withoutMusic = (x) => (x ? {...x, music: NO_MUSIC} : x);
