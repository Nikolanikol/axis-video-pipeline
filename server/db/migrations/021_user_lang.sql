-- Язык человека (15.11, решение владельца): один переключатель RU · EN · SQ задаёт язык
-- интерфейса, слайдов, роликов и писем — аудитория международная.
--
-- Хранится у человека, а не у компании: письма (код, сброс пароля, оплата) уходят человеку,
-- в том числе по таймеру, когда запроса с языком браузера нет. Язык контента компании —
-- profile.language, его ставит тот же переключатель.
-- NULL — человек зарегистрирован до переводов: письма ему — по-русски, как было, а интерфейс
-- при первом входе берёт язык постов компании и записывает его сюда (app/config.tsx).
ALTER TABLE smmaker_users ADD COLUMN lang text CHECK (lang IN ('ru', 'en', 'sq'));
