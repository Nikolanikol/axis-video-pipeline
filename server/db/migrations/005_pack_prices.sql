-- Прайс пакетов (решение владельца 28 сентября) вместо черновых цен из 003.
--
-- Отсчёт — средний клиент: ~30 каруселей в месяц и 200 000 ₩. Кредитов в пакете в полтора
-- раза больше, чем публикаций: часть запусков уходит на переделки («не понравилось»,
-- «поправил данные»), а технические сбои и так возвращают кредиты сами. Вдвое не стали:
-- тогда «Месяца» хватало бы на полтора, и средний клиент платил бы ~140 тыс. в месяц.
-- «Старт» дороже за кредит намеренно — это проба, основным пакетом должен быть «Месяц».
--   Старт    15 кр. / 100 000 ₩ — 6 667 ₩ за кредит
--   Месяц    45 кр. / 200 000 ₩ — 4 444 ₩
--   Квартал 135 кр. / 500 000 ₩ — 3 704 ₩ (объём на три месяца; сам пакет живёт год)
-- id прежние: на них могут ссылаться проданные партии, а цена партии записана в ней самой.

UPDATE smmaker_packs SET title = 'Старт',   credits = 15,  price_krw = 100000, sort = 1 WHERE id = 'start';
UPDATE smmaker_packs SET title = 'Месяц',   credits = 45,  price_krw = 200000, sort = 2 WHERE id = 'base';
UPDATE smmaker_packs SET title = 'Квартал', credits = 135, price_krw = 500000, sort = 3 WHERE id = 'pro';

-- «Бизнес» из черновика убираем. Если его уже продавали — только снимаем с продажи,
-- удалить нельзя: на него ссылаются партии
UPDATE smmaker_packs SET active = false WHERE id = 'business';
DELETE FROM smmaker_packs p WHERE id = 'business'
  AND NOT EXISTS (SELECT 1 FROM smmaker_credit_lots l WHERE l.pack_id = p.id);
