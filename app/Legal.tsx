// Дата редакции: меняется вместе с условиями. Клиент, купивший раньше, живёт по редакции дня оплаты
const EDITION = '12 октября 2026 г.';
// Оферта поменялась в тот же день (возврат 14 дней → 3 суток, вечер 12.10) — вторая редакция того же
// числа. Клиент, оплативший до неё, вправе требовать возврат по первой (14 дней)
const OFFER_EDITION = '12 октября 2026 г. (вторая, возврат — 3 суток)';

export type LegalKind = 'offer' | 'privacy';

const won = (n: number) => `${n.toLocaleString('ru-RU')} ₩`;
const credits = (n: number) => {
  const d = n % 10; const h = n % 100;
  return `${n} ${d === 1 && h !== 11 ? 'кредит' : d >= 2 && d <= 4 && (h < 12 || h > 14) ? 'кредита' : 'кредитов'}`;
};

/** Контакты платформы ссылками: WhatsApp, Telegram, почта — что заполнено в config/platform.json */
export const contactLinks = (c: Offer['contacts'] | undefined) => {
  const out: {label: string; value: string; href: string}[] = [];
  // Telegram — первым: главный канал поддержки (владелец 12.10). Пишут и «@ник», и ссылкой — ведём на t.me
  const tg = c?.telegram?.trim().replace(/^https?:\/\/t\.me\//, '').replace(/^@/, '');
  if (tg) out.push({label: 'Telegram', value: `@${tg}`, href: `https://t.me/${tg}`});
  const wa = c?.whatsapp?.replace(/\D/g, '');
  if (wa) out.push({label: 'WhatsApp', value: c!.whatsapp!, href: `https://wa.me/${wa}`});
  if (c?.email) out.push({label: 'Почта', value: c.email, href: `mailto:${c.email}`});
  // Instagram — ссылкой на профиль; показываем ник из адреса
  const ig = c?.instagram?.trim().replace(/[?#].*$/, '').replace(/\/+$/, '');
  if (ig) out.push({label: 'Instagram', value: `@${ig.split('/').pop()}`, href: ig.startsWith('http') ? ig : `https://www.instagram.com/${ig.replace(/^@/, '')}`});
  return out;
};

// Адрес сайта в документах — боевой из настроек, а не адрес страницы: на Mac и превью он другой,
// а модератор кассы и клиент должны видеть тот, где договор действует
const siteOf = (offer: PublicOffer | null) => offer?.legal?.site?.trim() || 'https://app.axis-beauty.com';

// Незаполненное поле видно сразу, а не пустым местом: с ним на модерацию кассы не идём
const Fill: React.FC<{v?: string; what: string}> = ({v, what}) =>
  v?.trim() ? <>{v}</> : <mark className="legal-fill">[заполнить: {what}]</mark>;

export const LegalPage: React.FC<{kind: LegalKind; anchor?: string}> = ({kind, anchor}) => {
  const [offer, setOffer] = useState<PublicOffer | null>(null);
  const [loaded, setLoaded] = useState(false);
  useEffect(() => { api.publicOffer().then(setOffer).catch(() => setOffer(null)).finally(() => setLoaded(true)); }, []);
  // #/offer/refunds — сразу к разделу (ссылка «Возврат денег» в подвале). Ждём ответа сервера:
  // таблица тарифов приходит с ним и сдвигает разделы ниже
  useEffect(() => { if (loaded && anchor) document.getElementById(anchor)?.scrollIntoView(); }, [loaded, anchor]);
  // Заголовок вкладки — свой у документа, при уходе на витрину возвращаем прежний
  useEffect(() => {
    const was = document.title;
    document.title = kind === 'offer' ? 'Публичная оферта — KOK' : 'Персональные данные — KOK';
    return () => { document.title = was; };
  }, [kind]);
  return (
    <div className="landing legal">
      <header className="land-top">
        <a href="#/" aria-label="KOK — на главную"><img src="/kok/wordmark.svg" alt="KOK" className="land-logo" /></a>
        <nav className="legal-tabs">
          <a href="#/offer" className={kind === 'offer' ? 'on' : ''}>Оферта</a>
          <a href="#/privacy" className={kind === 'privacy' ? 'on' : ''}><span className="legal-long">Персональные данные</span><span className="legal-short">Политика</span></a>
        </nav>
        <a className="btn ghost" href="#/"><ArrowLeft size={16} aria-hidden /><span className="legal-back">На главную</span></a>
      </header>
      <article className="legal-body">
        {kind === 'offer' ? <OfferText offer={offer} /> : <PrivacyText offer={offer} />}
        <Seller offer={offer} />
      </article>
    </div>
  );
};

