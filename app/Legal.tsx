//
// Зачем (12.10): платёжные сервисы (AnyPay, Lava) пускают сайт к приёму денег только после
// модерации, а модератор ищет оферту, правила возврата, контакты и описание услуги. Клиенту
// они тоже нужны: платит иностранному продавцу и должен видеть, кому и на каких условиях.
//
// Правила в тексте — те, по которым работает код, а не «как принято»: цены генераций и подарок
// приходят из config/credits.json, тарифы — из базы, сгорание и возврат кредита при сбое — как в
// server/billing.mjs. Меняешь поведение кредитов или оплаты — поправь и текст здесь, и дату редакции.
// Продавец и контакты — config/platform.json (legal, telegram), отдаёт GET /api/public/offer.
